constexpr auto limit = std::numeric_limits<std::size_t>::max();

std::size_t saturated_add(std::size_t a, std::size_t b) {
    return a > limit - b ? limit : a + b;
}

std::size_t saturated_multiply(std::size_t a, std::size_t b) {
    return b != 0 && a > limit / b ? limit : a * b;
}

constexpr std::uint64_t all_residues = ~std::uint64_t{0};

// Sumsets in Z/64: a set bit denotes one possible length residue. Rotation
// adds a residue without overflowing absolute byte lengths. Iterate the
// smaller operand; singleton/empty/full sets are particularly cheap.
std::uint64_t residue_sum(std::uint64_t a, std::uint64_t b) {
    if (!a || !b) return 0;
    if (a == all_residues || b == all_residues) return all_residues;
    if (std::has_single_bit(a)) return std::rotl(b, std::countr_zero(a));
    if (std::has_single_bit(b)) return std::rotl(a, std::countr_zero(b));
    if (std::popcount(a) > std::popcount(b)) std::swap(a, b);
    std::uint64_t result = 0;
    while (a) {
        result |= std::rotl(b, std::countr_zero(a));
        if (result == all_residues) break;
        a &= a - 1;
    }
    return result;
}

std::uint64_t residue_power(std::uint64_t body, std::size_t count) {
    std::uint64_t result = 1; // epsilon
    while (count) {
        if (count & 1) result = residue_sum(result, body);
        count >>= 1;
        if (count) body = residue_sum(body, body);
    }
    return result;
}

std::uint64_t residue_repeat(std::uint64_t body, std::size_t lower,
                             std::optional<std::size_t> upper) {
    if (upper) {
        // Padding with epsilon makes (B union epsilon)^(U-L) exactly the
        // union of powers 0..U-L. No U+1, integer powers, or count-sized loop.
        return residue_sum(residue_power(body, lower),
                           residue_power(body | 1, *upper - lower));
    }
    if (!body) return lower == 0 ? 1 : 0;
    // In this finite cyclic group the nonnegative closure is the subgroup
    // generated by B. Arbitrarily long zero-sum padding satisfies any lower
    // bound, so unbounded repetition has the same residues for every L.
    unsigned step = 64;
    while (body) {
        step = std::gcd(step, static_cast<unsigned>(std::countr_zero(body)));
        if (step == 1) return all_residues;
        body &= body - 1;
    }
    std::uint64_t result = 0;
    for (unsigned bit = 0; bit < 64; bit += step) result |= std::uint64_t{1} << bit;
    return result;
}

// Truncated nonnegative sumsets. Dropping sums >= 64 is exact for this
// bounded observation: no later concatenation can make a length smaller.
std::uint64_t short_sum(std::uint64_t a, std::uint64_t b) {
    if (!a || !b) return 0;
    if (a == all_residues) return all_residues << std::countr_zero(b);
    if (b == all_residues) return all_residues << std::countr_zero(a);
    if (std::has_single_bit(a)) return b << std::countr_zero(a);
    if (std::has_single_bit(b)) return a << std::countr_zero(b);
    if (std::popcount(a) > std::popcount(b)) std::swap(a, b);
    std::uint64_t result = 0;
    while (a) {
        result |= b << std::countr_zero(a);
        if (result == all_residues) break;
        a &= a - 1;
    }
    return result;
}

std::uint64_t short_power(std::uint64_t body, std::size_t count) {
    std::uint64_t result = 1;
    while (count) {
        if (count & 1) result = short_sum(result, body);
        if (!result) break;
        count >>= 1;
        if (count) body = short_sum(body, body);
    }
    return result;
}

std::uint64_t short_repeat(std::uint64_t body, std::size_t lower,
                           std::optional<std::size_t> upper) {
    const auto mandatory = short_power(body, lower);
    if (!mandatory) return 0;
    if (upper)
        return short_sum(mandatory, short_power(body | 1, *upper - lower));
    if (body & 2) return short_sum(mandatory, all_residues);
    // Any total < 64 uses at most 63 nonempty factors. Empty factors can be
    // omitted, so six squarings of B union epsilon give its complete closure.
    auto closure = body | 1;
    for (unsigned i = 0; i < 6; ++i) {
        const auto next = short_sum(closure, closure);
        if (next == closure) break;
        closure = next;
    }
    return short_sum(mandatory, closure);
}

constexpr OccurrenceLength epsilon_suffix{true, 0, 0, 0, 1, 1};
OccurrenceLength empty_word() { return epsilon_suffix; }
OccurrenceLength unknown() { return {true, 0, 0, 1}; }

OccurrenceLength unite(OccurrenceLength a, const OccurrenceLength& b) {
    if (!a.productive) return b;
    if (!b.productive) return a;
    const auto difference = a.offset >= b.offset ? a.offset - b.offset : b.offset - a.offset;
    a.minimum = std::min(a.minimum, b.minimum);
    a.modulus = std::gcd(std::gcd(a.modulus, b.modulus), difference);
    a.residues |= b.residues;
    a.short_lengths |= b.short_lengths;
    // Canonical representatives make convergence independent of visitation.
    if (a.modulus) a.offset %= a.modulus;
    return a;
}

OccurrenceLength concatenate(const OccurrenceLength& a, const OccurrenceLength& b) {
    if (!a.productive || !b.productive) return {};
    OccurrenceLength result{true, saturated_add(a.minimum, b.minimum), 0,
                            std::gcd(a.modulus, b.modulus),
                            residue_sum(a.residues, b.residues),
                            short_sum(a.short_lengths, b.short_lengths)};
    if (a.offset > limit - b.offset) {
        // Losing a congruence on arithmetic overflow is safe; wrapping one is
        // not. The separately saturated lower bound still rejects short input.
        result.modulus = 1;
    } else {
        result.offset = a.offset + b.offset;
        if (result.modulus) result.offset %= result.modulus;
    }
    return result;
}

OccurrenceLength repetition(const OccurrenceLength& body, std::size_t lower,
                            std::optional<std::size_t> upper) {
    if (upper && *upper < lower) return {};
    if ((upper && *upper == 0) || !body.productive)
        return lower == 0 ? empty_word() : OccurrenceLength{};
    OccurrenceLength result{true, saturated_multiply(lower, body.minimum), 0, 0};
    result.residues = residue_repeat(body.residues, lower, upper);
    result.short_lengths = short_repeat(body.short_lengths, lower, upper);
    // Multiple iterations are independent derivations. For a fixed positive
    // count the body modulus is retained, not multiplied by the count.
    result.modulus = upper && *upper == lower
        ? body.modulus : std::gcd(body.modulus, body.offset);
    if (lower && body.offset > limit / lower) {
        result.modulus = 1;
    } else {
        result.offset = lower * body.offset;
        if (result.modulus) result.offset %= result.modulus;
    }
    return result;
}

bool same(const OccurrenceLength& a, const OccurrenceLength& b) {
    return a.productive == b.productive && a.minimum == b.minimum &&
           a.offset == b.offset && a.modulus == b.modulus && a.residues == b.residues &&
           a.short_lengths == b.short_lengths;
}

// Width extraction also proves the absence of environment/source effects.
// In particular, an exact length summary alone does not justify erasing a
// capture, call, reference, or binding from a height equation.
std::optional<std::size_t> fixed_width(const Ast& ast, NodeId id,
                                     const std::vector<OccurrenceLength>& lengths) {
    const auto& node = ast.nodes[id];
    if (node.kind == Kind::Capture || node.kind == Kind::Call ||
        node.kind == Kind::Reference || node.kind == Kind::Define ||
        node.bind_count != no_id || node.use_count != no_id || node.count_path != no_id)
        return {};
    for (const auto child : node.children)
        if (!fixed_width(ast, child, lengths)) return {};
    const auto& summary = lengths[id];
    if (!summary.productive || summary.modulus != 0 || summary.minimum != summary.offset)
        return {};
    return summary.offset;
}

void flatten_concat(const Ast& ast, NodeId id, std::vector<NodeId>& output) {
    if (ast.nodes[id].kind == Kind::Concat) {
        for (const auto child : ast.nodes[id].children) flatten_concat(ast, child, output);
    } else {
        output.push_back(id);
    }
}

bool add_exact(std::size_t& total, std::size_t amount) {
    if (total > limit - amount) return false;
    total += amount;
    return true;
}

std::optional<OccurrenceHeightEquation> extract_height_equation(
    const Ast& ast, const std::vector<OccurrenceLength>& lengths) {
    if (ast.root >= ast.nodes.size() || !ast.has_occurrence_paths) return {};
    std::vector<NodeId> root_parts;
    flatten_concat(ast, ast.root, root_parts);
    NodeId source = no_id;
    for (const auto id : root_parts) {
        const auto& node = ast.nodes[id];
        if (node.kind != Kind::Call && node.kind != Kind::Capture) continue;
        if (source != no_id) return {};
        source = node.kind == Kind::Call ? node.call_target : id;
        if (source >= ast.nodes.size() || ast.nodes[source].kind != Kind::Capture)
            return {};
    }
    if (source == no_id) return {};
    const auto& source_node = ast.nodes[source];
    if (source_node.capture_id == no_id || source_node.children.size() != 1) return {};
    const auto& body = ast.nodes[source_node.children.front()];
    if (body.kind != Kind::Alt) return {};
    std::optional<std::size_t> base_width, recursive_width;
    for (const auto branch : body.children) {
        std::vector<NodeId> branch_parts;
        flatten_concat(ast, branch, branch_parts);
        bool recursive = false;
        std::size_t width = 0;
        for (const auto part : branch_parts) {
            const auto& node = ast.nodes[part];
            if (node.kind == Kind::Call && node.call_target == source) {
                if (recursive) return {};
                recursive = true;
                continue;
            }
            const auto fixed = fixed_width(ast, part, lengths);
            if (!fixed || !add_exact(width, *fixed)) return {};
        }
        auto& expected = recursive ? recursive_width : base_width;
        if (expected && *expected != width) return {};
        expected = width;
    }
    if (!base_width || !recursive_width) return {};
    OccurrenceHeightEquation equation;
    equation.capture_id = source_node.capture_id;
    equation.offset = *base_width;
    equation.coefficient = *recursive_width;
    bool entered_source = false;
    for (const auto part : root_parts) {
        const auto& node = ast.nodes[part];
        if (node.kind == Kind::Define) continue;
        if (part == source || (node.kind == Kind::Call && node.call_target == source)) {
            entered_source = true;
            continue;
        }
        if (node.kind == Kind::Repeat && node.count_path != no_id) {
            if (!entered_source || node.count_path >= ast.count_paths.size() ||
                node.children.size() != 1 || node.bind_count != no_id)
                return {};
            const auto& path = ast.count_paths[node.count_path];
            if (path.anchor != OccurrenceAnchor::Root || path.parents != 0 ||
                path.metric != OccurrenceMetric::Height || path.steps.size() != 1)
                return {};
            const auto& step = path.steps.front();
            if (step.source != OccurrenceSource::Group || step.id != equation.capture_id ||
                (step.index && *step.index != 0))
                return {};
            const auto width = fixed_width(ast, node.children.front(), lengths);
            if (!width || !add_exact(equation.coefficient, *width)) return {};
            equation.count_paths.push_back(node.count_path);
            continue;
        }
        const auto width = fixed_width(ast, part, lengths);
        if (!width || !add_exact(equation.offset, *width)) return {};
    }
    if (equation.count_paths.empty() || equation.coefficient == 0) return {};
    return equation;
}

OccurrenceLength evaluate(const Ast& ast, NodeId id,
                          const std::vector<OccurrenceLength>& lengths) {
    const auto& node = ast.nodes[id];
    switch (node.kind) {
    case Kind::Empty:
    case Kind::Define:
        return empty_word();
    case Kind::CharSet:
        return node.characters.any() ? OccurrenceLength{true, 1, 1, 0, 2, 2}
                                     : OccurrenceLength{};
    case Kind::Reference:
        return unknown();
    case Kind::Call:
        return node.call_target < lengths.size() ? lengths[node.call_target] : unknown();
    case Kind::Capture:
        return node.children.empty() ? empty_word() : lengths[node.children.front()];
    case Kind::Concat: {
        if (node.children.empty()) return empty_word();
        // The first child's summary is already the result of composing it
        // with epsilon. Avoid that identity operation on every evaluation,
        // while preserving the original left-to-right association.
        auto result = lengths[node.children.front()];
        for (std::size_t i = 1; i < node.children.size(); ++i)
            result = concatenate(result, lengths[node.children[i]]);
        return result;
    }
    case Kind::Alt: {
        if (node.children.empty()) return {};
        auto result = lengths[node.children.front()];
        for (std::size_t i = 1; i < node.children.size(); ++i)
            result = unite(result, lengths[node.children[i]]);
        return result;
    }
    case Kind::Repeat: {
        if (node.children.empty()) return unknown();
        // A binding chooses within its declared range. A use is evaluated in
        // the incoming environment, and can be any nonnegative count here.
        const bool dynamic = node.use_count != no_id || node.count_path != no_id;
        return repetition(lengths[node.children.front()], dynamic ? 0 : node.lower,
                          dynamic ? std::optional<std::size_t>{} : node.upper);
    }
    }
    return unknown();
}

OccurrenceBoundary boundary_unknown() {
    OccurrenceBoundary result;
    result.nullable = true;
    result.first.set();
    result.last.set();
    return result;
}

OccurrenceBoundary evaluate_boundary(const Ast& ast, NodeId id,
    const std::vector<OccurrenceLength>& lengths,
    const std::vector<OccurrenceByteConditions>& conditions) {
    const auto boundary = [&](NodeId child) -> const OccurrenceBoundary& {
        return conditions[child].boundary;
    };
    const auto& node = ast.nodes[id];
    OccurrenceBoundary result;
    switch (node.kind) {
    case Kind::Empty:
    case Kind::Define:
        result.nullable = true;
        break;
    case Kind::CharSet:
        result.first = result.last = node.characters;
        break;
    case Kind::Reference:
        return boundary_unknown();
    case Kind::Call:
        return node.call_target < conditions.size()
            ? boundary(node.call_target) : boundary_unknown();
    case Kind::Capture:
        if (!node.children.empty()) return boundary(node.children.front());
        result.nullable = true;
        break;
    case Kind::Alt:
        for (const auto child : node.children) {
            const auto& value = boundary(child);
            result.nullable |= value.nullable;
            result.first |= value.first;
            result.last |= value.last;
        }
        break;
    case Kind::Concat:
        // FIRST of a prefix is irrelevant if a later child has no finite
        // derivation. Productivity here comes from the completed length fixed
        // point, never an unfinished approximation of a recursive child.
        for (const auto child : node.children)
            if (!lengths[child].productive) return {};
        result.nullable = true;
        for (const auto child : node.children) {
            result.first |= boundary(child).first;
            if (!boundary(child).nullable) { result.nullable = false; break; }
        }
        for (auto it = node.children.rbegin(); it != node.children.rend(); ++it) {
            result.last |= boundary(*it).last;
            if (!boundary(*it).nullable) break;
        }
        break;
    case Kind::Repeat: {
        if (node.children.empty()) return boundary_unknown();
        const bool dynamic = node.use_count != no_id || node.count_path != no_id;
        const auto lower = dynamic ? 0 : node.lower;
        const auto upper = dynamic ? std::optional<std::size_t>{} : node.upper;
        if (upper && *upper < lower) return {};
        const auto child = node.children.front();
        result.nullable = lower == 0 || boundary(child).nullable;
        if ((!upper || *upper != 0) && lengths[child].productive) {
            result.first = boundary(child).first;
            result.last = boundary(child).last;
        }
        break;
    }
    }
    return result;
}

std::uint64_t byte_residues(const std::bitset<256>& bytes) {
    const std::bitset<256> low{all_residues};
    return (bytes & low).to_ullong() | ((bytes >> 64) & low).to_ullong() |
           ((bytes >> 128) & low).to_ullong() | ((bytes >> 192) & low).to_ullong();
}

std::uint64_t pair_cross(std::uint64_t first, std::uint64_t second) {
    // Multiplication by 17 permutes Z/64. Since 17*r = r + 16*(r mod 4),
    // four disjoint rotations avoid a per-byte Cartesian-product loop.
    const auto weighted = (first & 0x1111111111111111ULL) |
        std::rotl(first & std::uint64_t{0x2222222222222222ULL}, 16) |
        std::rotl(first & std::uint64_t{0x4444444444444444ULL}, 32) |
        std::rotl(first & std::uint64_t{0x8888888888888888ULL}, 48);
    return residue_sum(weighted, second);
}

void compile_pairs(const Ast& ast,
    const std::vector<OccurrenceLength>& lengths,
    std::vector<OccurrenceByteConditions>& conditions) {
    const auto boundary = [&](NodeId child) -> const OccurrenceBoundary& {
        return conditions[child].boundary;
    };
    const auto pairs = [&](NodeId node) -> OccurrencePairs& {
        return conditions[node].pairs;
    };
    struct Bytes { std::uint64_t first, last, single; };
    struct Link { NodeId parent, next; unsigned char directions; };
    constexpr unsigned char prefix = 1, suffix = 2, both = 3;
    const auto size = ast.nodes.size();
    std::vector<Bytes> bytes;
    bytes.reserve(size);
    for (NodeId id = 0; id < size; ++id) {
        const auto& b = boundary(id);
        // Every one-byte word lies in FIRST intersect LAST. Testing length 1
        // tightens this safe approximation without introducing a second
        // recursive language analysis for singleton words.
        bytes.push_back({byte_residues(b.first), byte_residues(b.last),
            lengths[id].accepts(1) ? byte_residues(b.first & b.last) : 0});
    }
    // A forward-star graph avoids one small allocation per dependency list.
    // At most one edge is emitted per structural child (directions merge),
    // plus one for a call target. Indices survive vector growth and moves.
    std::vector<NodeId> heads(size, no_id);
    std::vector<Link> links;
    std::size_t capacity = 0;
    for (const auto& node : ast.nodes) {
        if (node.children.size() > links.max_size() - capacity)
            throw std::length_error("too many byte-pair dependencies");
        capacity += node.children.size();
        if (node.kind == Kind::Call) {
            if (capacity == links.max_size())
                throw std::length_error("too many byte-pair dependencies");
            ++capacity;
        }
    }
    links.reserve(capacity);
    const auto link = [&](NodeId child, NodeId parent, unsigned char directions) {
        links.push_back({parent, heads[child], directions});
        heads[child] = links.size() - 1;
    };
    for (NodeId id = 0; id < size; ++id) {
        if (!lengths[id].productive) continue;
        const auto& node = ast.nodes[id];
        auto& seed = pairs(id);
        switch (node.kind) {
        case Kind::Empty: case Kind::Define: case Kind::CharSet:
            break;
        case Kind::Reference:
            seed = {all_residues, all_residues};
            break;
        case Kind::Call:
            if (node.call_target < size) link(node.call_target, id, both);
            else seed = {all_residues, all_residues};
            break;
        case Kind::Capture:
            if (!node.children.empty()) link(node.children.front(), id, both);
            break;
        case Kind::Alt:
            for (const auto child : node.children) link(child, id, both);
            break;
        case Kind::Concat: {
            // Pair contributions crossing child boundaries depend only on
            // completed byte/nullability facts, so compute them once. A
            // prefix can cross a boundary only when its preceding part can
            // be exactly one byte (with any number of empty children).
            std::uint64_t single = 0;
            bool nullable = true;
            for (const auto child : node.children) {
                seed.first |= pair_cross(single, bytes[child].first);
                single = (boundary(child).nullable ? single : 0) |
                         (nullable ? bytes[child].single : 0);
                nullable &= boundary(child).nullable;
                if (!nullable && !single) break;
            }
            single = 0; nullable = true;
            for (auto it = node.children.rbegin(); it != node.children.rend(); ++it) {
                seed.last |= pair_cross(bytes[*it].last, single);
                single = (boundary(*it).nullable ? single : 0) |
                         (nullable ? bytes[*it].single : 0);
                nullable &= boundary(*it).nullable;
                if (!nullable && !single) break;
            }
            // Pairs wholly within one child can reach the front through an
            // empty prefix, or the back through an empty suffix. Stop each
            // dependency range after including its first nonnullable child.
            auto first_stop = node.children.size();
            std::size_t last_start = 0;
            for (std::size_t i = 0; i < node.children.size(); ++i)
                if (!boundary(node.children[i]).nullable) { first_stop = i; break; }
            for (std::size_t i = node.children.size(); i-- > 0;)
                if (!boundary(node.children[i]).nullable) { last_start = i; break; }
            for (std::size_t i = 0; i < node.children.size(); ++i) {
                const auto directions = static_cast<unsigned char>(
                    (i <= first_stop ? prefix : 0) | (i >= last_start ? suffix : 0));
                if (directions) link(node.children[i], id, directions);
            }
            break;
        }
        case Kind::Repeat: {
            if (node.children.empty()) { seed = {all_residues, all_residues}; break; }
            const bool dynamic = node.use_count != no_id || node.count_path != no_id;
            const auto lower = dynamic ? 0 : node.lower;
            const auto upper = dynamic ? std::optional<std::size_t>{} : node.upper;
            if ((upper && *upper < lower) || (upper && *upper == 0)) break;
            const auto child = node.children.front();
            if (!lengths[child].productive) break;
            link(child, id, both);
            if (!upper || *upper >= 2) {
                seed.first = pair_cross(bytes[child].single, bytes[child].first);
                seed.last = pair_cross(bytes[child].last, bytes[child].single);
            }
            break;
        }
        }
    }
    // Each equation is now a constant seed OR selected child masks. Propagate
    // only newly discovered bits; recursive updates do no further sumsets.
    std::vector<OccurrencePairs> sent(size);
    std::vector<bool> queued(size, false);
    std::deque<NodeId> pending;
    for (NodeId id = 0; id < size; ++id)
        if (pairs(id).first || pairs(id).last) { pending.push_back(id); queued[id] = true; }
    while (!pending.empty()) {
        const auto id = pending.front(); pending.pop_front(); queued[id] = false;
        const OccurrencePairs delta{pairs(id).first & ~sent[id].first,
                                    pairs(id).last & ~sent[id].last};
        sent[id] = pairs(id);
        for (auto index = heads[id]; index != no_id; index = links[index].next) {
            const auto& edge = links[index];
            auto& target = pairs(edge.parent);
            const auto first = edge.directions & prefix ? delta.first & ~target.first : 0;
            const auto last = edge.directions & suffix ? delta.last & ~target.last : 0;
            if (!first && !last) continue;
            target.first |= first; target.last |= last;
            if (!queued[edge.parent]) { pending.push_back(edge.parent); queued[edge.parent] = true; }
        }
    }
}

