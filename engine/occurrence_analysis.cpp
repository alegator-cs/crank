bool OccurrenceLength::accepts(std::size_t size) const {
    if (!productive || size < minimum) return false;
    if (modulus == 0) return size == offset; // singleton already decides
    if (size < 64 && (short_lengths & (std::uint64_t{1} << size)) == 0) return false;
    if ((residues & (std::uint64_t{1} << (size & 63))) == 0) return false;
    return modulus == 1 || size % modulus == offset % modulus;
}

std::optional<std::size_t> OccurrenceHeightEquation::height_for_length(std::size_t size) const {
    if (coefficient == 0 || size < offset || (size - offset) % coefficient != 0) return {};
    return (size - offset) / coefficient;
}

bool OccurrenceHeightEquation::accepts(std::size_t size) const {
    return height_for_length(size).has_value();
}

OccurrenceAnalysis::OccurrenceAnalysis(const Ast& ast)
    : lengths_(ast.nodes.size()), byte_conditions_(ast.nodes.size()), suffix_minima_(ast.nodes.size()),
      suffix_ranges_(ast.nodes.size()) {
    std::size_t suffix_count = 0;
    std::vector<std::vector<NodeId>> dependants(ast.nodes.size());
    for (NodeId id = 0; id < ast.nodes.size(); ++id) {
        const auto& node = ast.nodes[id];
        if (node.kind == Kind::Concat && node.children.size() > 1) {
            const auto count = node.children.size() - 1;
            if (count > suffix_lengths_.max_size() - suffix_count)
                throw std::length_error("too many concatenation suffixes");
            suffix_count += count;
        }
        if (node.kind != Kind::Define)
            for (const auto child : node.children) dependants[child].push_back(id);
        if (node.kind == Kind::Call && node.call_target < ast.nodes.size())
            dependants[node.call_target].push_back(id);
    }
    std::deque<NodeId> pending;
    std::vector<bool> queued(ast.nodes.size(), true);
    for (NodeId id = 0; id < ast.nodes.size(); ++id) pending.push_back(id);
    while (!pending.empty()) {
        const auto id = pending.front();
        pending.pop_front();
        queued[id] = false;
        // Union is monotone even when an earlier approximation had no body
        // derivation and a zero-count repeat initially contributed epsilon.
        const auto next = unite(lengths_[id], evaluate(ast, id, lengths_));
        if (same(next, lengths_[id])) continue;
        lengths_[id] = next;
        for (const auto parent : dependants[id]) {
            if (queued[parent]) continue;
            queued[parent] = true;
            pending.push_back(parent);
        }
    }
    // Reuse the dependency graph, but keep this finite byte-set fixed point
    // separate. Extra byte updates must not reschedule arithmetic evaluation
    // or change its established saturated-overflow behavior.
    std::fill(queued.begin(), queued.end(), true);
    for (NodeId id = 0; id < ast.nodes.size(); ++id) pending.push_back(id);
    while (!pending.empty()) {
        const auto id = pending.front(); pending.pop_front(); queued[id] = false;
        auto next = evaluate_boundary(ast, id, lengths_, byte_conditions_);
        next.nullable |= byte_conditions_[id].boundary.nullable;
        next.first |= byte_conditions_[id].boundary.first;
        next.last |= byte_conditions_[id].boundary.last;
        if (next == byte_conditions_[id].boundary) continue;
        byte_conditions_[id].boundary = next;
        for (const auto parent : dependants[id]) {
            if (queued[parent]) continue;
            queued[parent] = true;
            pending.push_back(parent);
        }
    }
    compile_pairs(ast, lengths_, byte_conditions_);
    suffix_lengths_.reserve(suffix_count);
    for (NodeId id = 0; id < ast.nodes.size(); ++id) {
        const auto& node = ast.nodes[id];
        if (node.kind != Kind::Concat) continue;
        auto& suffix = suffix_minima_[id];
        suffix.resize(node.children.size() + 1, 0);
        if (node.children.empty()) continue;
        auto& range = suffix_ranges_[id];
        range = {suffix_lengths_.size(), node.children.back()};
        // The last child already owns its complete length summary, and all
        // terminal boundaries share epsilon. Retain only genuinely composed
        // suffixes, without pointers into this copyable analysis object.
        auto length = lengths_[range.last_child];
        suffix[node.children.size() - 1] = length.minimum;
        // Only the completed fixed point is safe to compose: a recursive
        // child's intermediate approximation can omit valid derivations.
        // Keep the original right fold even at boundary zero: overflow can
        // make it differ from the node summary, which was folded left.
        for (std::size_t i = node.children.size() - 1; i-- > 0;) {
            length = concatenate(lengths_[node.children[i]], length);
            suffix_lengths_.push_back(length);
            suffix[i] = length.minimum;
        }
    }
    height_equation_ = extract_height_equation(ast, lengths_);
}

const OccurrenceLength& OccurrenceAnalysis::length(NodeId id) const { return lengths_.at(id); }

const OccurrenceBoundary& OccurrenceAnalysis::boundary(NodeId id) const { return byte_conditions_.at(id).boundary; }

const OccurrencePairs& OccurrenceAnalysis::pairs(NodeId id) const { return byte_conditions_.at(id).pairs; }

const OccurrenceByteConditions& OccurrenceAnalysis::byte_conditions(NodeId id) const {
    return byte_conditions_.at(id);
}

const std::vector<std::size_t>& OccurrenceAnalysis::suffix_minimum(NodeId id) const {
    return suffix_minima_.at(id);
}

const OccurrenceLength& OccurrenceAnalysis::suffix_length(NodeId id, std::size_t boundary) const {
    const auto size = suffix_minima_.at(id).size();
    if (boundary >= size) throw std::out_of_range("concatenation suffix boundary");
    if (boundary == size - 1) return epsilon_suffix;
    const auto& range = suffix_ranges_[id];
    if (boundary == size - 2) return lengths_[range.last_child];
    return suffix_lengths_[range.base + size - 3 - boundary];
}

const std::optional<OccurrenceHeightEquation>& OccurrenceAnalysis::height_equation() const {
    return height_equation_;
}

